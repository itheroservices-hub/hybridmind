/**
 * Writes a real node_modules/vscode package pointing at the compiled test
 * mock (test-out/test/mocks/vscode.js), so `import * as vscode from
 * 'vscode'` in src/ resolves through Node's normal module resolution
 * during tests, no runtime patching of Module internals required, which
 * is fragile across Node/Mocha versions (as the ESM-vs-CJS spec-file
 * loading behavior that motivated this file demonstrated directly).
 *
 * node_modules/ is gitignored, so this runs as part of `pretest`, after
 * the TypeScript build, so it exists fresh on every `npm test`.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const shimDir = path.join(root, 'node_modules', 'vscode');
const compiledMockPath = path
  .join(root, 'test-out', 'test', 'mocks', 'vscode.js')
  .replace(/\\/g, '\\\\');

fs.mkdirSync(shimDir, { recursive: true });

fs.writeFileSync(
  path.join(shimDir, 'package.json'),
  JSON.stringify({ name: 'vscode', version: '0.0.0-test-shim', main: 'index.js' }, null, 2)
);

fs.writeFileSync(
  path.join(shimDir, 'index.js'),
  `// Generated by test/create-vscode-shim.js, do not edit directly.\n` +
  `module.exports = require("${compiledMockPath}");\n`
);

console.log('[create-vscode-shim] wrote node_modules/vscode shim ->', compiledMockPath);
